/** While pictures have the GPUs, chat is paused: say so above the composer, with the way back. */
function syncModeNote() {
  const mode = status.status?.mode;
  const pictures = mode && (mode.current === "images" || mode.requested === "images");
  const back = mode?.requested === "chat" && mode.current === "images";
  const key = pictures ? `${mode.current}|${mode.requested}|${mode.state}` : null;
  if (key === syncModeNote.shown) return;
  syncModeNote.shown = key;
  els.modeNote.hidden = !pictures;
  if (!pictures) return els.modeNote.replaceChildren();
  const switchBack = h("button", { class: "button", type: "button", text: back ? "Switching…" : "Switch to chat", disabled: back });
  switchBack.addEventListener("click", async () => {
    switchBack.disabled = true;
    switchBack.textContent = "Switching…";
    try {
      await api.setMode("chat");
      await status.refresh();
    } catch (err) {
      showNotice(err.message);
      switchBack.disabled = false;
      switchBack.textContent = "Switch to chat";
    }
  });
  els.modeNote.replaceChildren(
    h("span", { class: "mode-dot", "aria-hidden": "true" }),
    h("span", { class: "mode-text", text: back ? "Switching the GPUs back to chat. This takes about a minute." : "The GPUs are making pictures, so chat is paused." }),
    h("a", { class: "button button-quiet", href: IMAGES_PATH, text: "Open Images", onclick: (e) => { e.preventDefault(); go(IMAGES_PATH); } }),
    switchBack,
  );
}

async function openChat(id) {
  if (state.generation && state.generation.chatId !== id) state.generation.autoContinuationCancelled = true;
  const known = id === null ? null : sidebar.find(id);
  if ((state.chat?.id ?? null) !== id) {
    state.chat = known ?? (id === null ? null : { id, title: '', message_count: 0 });
    state.messages = [];
  }
  composer.switchDraft(id);
  syncAnswerNow();
  leaveImages();
  stopFollow();
  closePopover({ restoreFocus: false });
  sidebar.closeDrawer();
  hideNotice();
  state.loadAbort?.abort();
  state.loadingChatId = id;
  composer.setPreparing(Boolean(id) || state.longInputPreparing || state.sendPreparing);
  sidebar.setActive(id);
  longInputView.setSources([]);

  if (id === null) {
    state.chat = null;
    state.messages = [];
    setTitle(null);
    thread.showEmpty({ label: modelLabel(), modelSize: status.status?.model_size || "27B", numCtx: status.status?.num_ctx, active: contextReady(status.status) });
    els.conversation.scrollTop = 0;
    state.stickToBottom = true;
    telemetry.setChat(state.messages);
    telemetry.render();
    contextView.refresh({ immediate: true, force: true });
    els.jump.hidden = true;
    composer.focus();
    return;
  }

  // Returning to the chat this page is generating in: its live view is still attached to it.
  const live = state.generation?.chatId === id ? state.generation : null;
  const abort = (state.loadAbort = new AbortController());
  // The route owns the composer immediately; an older chat must not receive a
  // message typed while this chat's network load is still in flight.
  setTitle(known);
  if (!live) els.thread.replaceChildren(loadingPlaceholder());

  try {
    const { chat, messages } = await api.getChat(id, abort.signal);
    if (abort.signal.aborted) return;
    state.chat = chat;
    state.messages = messages;
    setTitle(chat);
    // A checkpoint and its active view are the same assistant message. Recheck
    // after the fetch: the generation may have finished while it was pending.
    const activeLive = state.generation?.chatId === id ? state.generation : null;
    const activeMessageId = Number(activeLive?.view.el.dataset.messageId);
    thread.render(activeLive && Number.isSafeInteger(activeMessageId) && activeMessageId > 0
      ? messages.filter(message => message.role !== "assistant" || message.id !== activeMessageId)
      : messages);
    decorateLongInputSources(els.thread, longInputView.sources, chat.id, location.origin);
    telemetry.setChat(messages);
    contextView.refresh({ immediate: true, force: true });
    if (activeLive) {
      const pending = activeLive.pendingUser;
      if (pending && !messages.some((m) => m.id === pending.id)) els.thread.append(pending.el);
      els.thread.append(activeLive.view.el);
    }
    loadLongInputs(id, abort.signal);
    state.stickToBottom = true;
    scrollToBottom(false);
    composer.focus();
    // Another device may be writing a reply in this chat right now.
    status.refresh().then(syncFollow);
  } catch (err) {
    if (abort.signal.aborted) return;
    if (err instanceof ApiError && err.status === 404) {
      toast("That chat doesn't exist anymore.");
      sidebar.remove(id);
      navigate("/", { replace: true });
      return;
    }
    els.thread.replaceChildren();
    showNotice(`Couldn't open this chat: ${err.message}`);
  } finally {
    if (state.loadAbort === abort) {
      state.loadingChatId = null;
      composer.setPreparing(state.longInputPreparing || state.sendPreparing);
    }
  }
}

