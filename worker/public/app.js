/** Starts the server on Kaggle; the banner then follows its start-up. */
async function startServer() {
  try {
    await api.startServer();
    toast("Starting on Kaggle. The banner will show its progress.", { tone: "ok" });
  } catch (err) {
    toast(err.message, { tone: "err" });
  }
  await status.refresh();
}

/** Asks the running notebook to shut down (it checks about once a minute), after a confirmation. */
async function shutDownServer() {
  const host = status.status?.host === "kaggle" ? "Kaggle" : "the";
  const ok = await confirmDialog({
    title: "Shut down the server?",
    message: `The ${host} notebook stops within a minute and its GPU time stops counting. Starting it again takes a few minutes.`,
    confirmLabel: "Shut down",
    danger: true,
  });
  if (!ok) return;
  try {
    await api.shutdownServer();
    toast("Shutting down. The notebook stops within a minute.", { tone: "ok" });
  } catch (err) {
    showNotice(`Couldn't shut the server down: ${err.message}`);
  }
  await status.refresh();
}

