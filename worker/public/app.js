async function renameChat(chat) {
  const title = await promptDialog({ title: "Rename chat", label: "Title", value: chat.title, confirmLabel: "Rename", maxLength: 80 });
  if (!title) return;
  try {
    updateChat(await api.renameChat(chat.id, title));
    toast("Chat renamed");
  } catch (err) {
    showNotice(`Couldn't rename the chat: ${err.message}`);
  }
}

async function exportChat(chat) {
  try {
    const { blob, filename } = await api.exportChat(chat.id);
    downloadBlob(blob, filename);
  } catch (err) {
    showNotice(`Couldn't export the chat: ${err.message}`);
  }
}

async function deleteChat(chat) {
  const ok = await confirmDialog({
    title: "Delete chat?",
    message: `“${chat.title || "New chat"}” and all its messages will be deleted. This can't be undone.`,
    confirmLabel: "Delete",
    danger: true,
  });
  if (!ok) return;
  try {
    await api.deleteChat(chat.id);
  } catch (err) {
    showNotice(err.code === "busy" ? "That chat is generating a reply. Stop it first, then delete." : `Couldn't delete the chat: ${err.message}`);
    return;
  }
  sidebar.remove(chat.id);
  toast("Chat deleted");
  if (state.chat?.id === chat.id) navigate("/", { replace: true });
  composer.forgetDraft(chat.id);
}

// ---------------------------------------------------------------- scrolling, notices, keys

function onScroll() {
  const el = els.conversation;
  const distance = el.scrollHeight - el.scrollTop - el.clientHeight;
  // Following only ever moves down, so any upward move is the reader's. Let go at once and
  // take hold again only at the real bottom; a 120px zone snapped a slow scroll back each frame.
  const up = el.scrollTop < lastScrollTop - 1 && distance > 1;
  lastScrollTop = el.scrollTop;
  if (up) state.stickToBottom = false;
  else if (distance < RESUME_FOLLOW_PX) state.stickToBottom = true;
  else if (!state.generation) state.stickToBottom = distance < NEAR_BOTTOM_PX;
  els.main.classList.toggle("is-scrolled", el.scrollTop > 2);
  els.main.classList.toggle("has-more", distance > 2);
  if (state.stickToBottom) els.jump.hidden = true;
}

function scrollToBottom(smooth) {
  const el = els.conversation;
  const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  el.scrollTo({ top: el.scrollHeight, behavior: smooth && !reduce ? "smooth" : "auto" });
  state.stickToBottom = true;
  els.jump.hidden = true;
}

function showNotice(message) {
  els.notice.replaceChildren(icon("alert"), Object.assign(document.createElement("span"), { textContent: message }));
  const close = document.createElement("button");
  close.type = "button";
  close.className = "icon-button notice-close";
  close.setAttribute("aria-label", "Dismiss");
  close.append(icon("close"));
  close.addEventListener("click", hideNotice);
  els.notice.append(close);
  els.notice.hidden = false;
}

function hideNotice() {
  els.notice.hidden = true;
  els.notice.replaceChildren();
}

function onKeydown(event) {
  const mod = event.ctrlKey || event.metaKey;
  const key = event.key.toLowerCase();
  if (mod && !event.shiftKey && key === "k") {
    event.preventDefault();
    sidebar.focusSearch();
  } else if (mod && event.shiftKey && key === "o") {
    event.preventDefault();
    newChat();
  } else if (mod && key === ",") {
    event.preventDefault();
    if (!document.querySelector("dialog[open]")) showSettings();
  } else if (event.key === "Escape" && !event.defaultPrevented) {
    if (document.querySelector("dialog[open]") || isPopoverOpen()) return;
    if (state.generation || state.compaction) {
      event.preventDefault();
      stop();
    } else if (sidebar.isDrawerOpen) {
      sidebar.closeDrawer();
    }
  }
}

